% Оголошення системи диференціальних рівнянь другого порядку
function dxdt = mySystem(~, x)
    % Параметри системи
    m = 1;  % маса
    c = 0.5;  % коефіцієнт згасання
    k = 2;  % коефіцієнт жорсткості
    
    % Визначення похідних
    dxdt = zeros(2, 1);
    dxdt(1) = x(2);
    dxdt(2) = (-c*x(2) - k*x(1)) / m;
end

% Часовий інтервал
tspan = [0 10];

% Початкові умови
x0 = [1; 0];  % початкове відхилення та початкова швидкість

% Крок
h = 0.1;

% Розв'язок системи методом Рунге-Кутта четвертого порядку
[t, x] = myRungeKutta(@mySystem, tspan, x0, h);

% Візуалізація результатів
plot(t, x(:, 1), 'b', t, x(:, 2), 'r');
xlabel('Час');
ylabel('Відхилення/Швидкість');
legend('Відхилення', 'Швидкість');
title('Чисельний розвязок стійкості системи другого порядку методом Рунге-Кутта четвертого порядку');

% Функція для методу Рунге-Кутта четвертого порядку
function [t, x] = myRungeKutta(f, tspan, x0, h)
    t = tspan(1):h:tspan(2);
    n = length(t);
    x = zeros(n, length(x0));
    x(1, :) = x0';
    for i = 1:n-1
        k1 = h * feval(f, t(i), x(i, :));
        k2 = h * feval(f, t(i) + h/2, x(i, :) + k1/2);
        k3 = h * feval(f, t(i) + h/2, x(i, :) + k2/2);
        k4 = h * feval(f, t(i) + h, x(i, :) + k3);
        x(i+1, :) = x(i, :) + (k1 + 2*k2 + 2*k3 + k4)/6;
    end
end
