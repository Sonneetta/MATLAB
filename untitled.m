% Налаштування параметрів
T = 10;         % Кінцевий час
dt = 0.01;      % Крок часу
N = T/dt;       % Кількість кроків

% Початкові умови
x0 = 1;         % Початкове значення x
v0 = 0;         % Початкове значення v
k = 1;          % Коефіцієнт пружності
m = 1;          % Маса

% Ініціалізація масивів
x = zeros(N, 1); % Масив для зберігання значень x
v = zeros(N, 1); % Масив для зберігання значень v
time = zeros(N, 1); % Масив для зберігання значень часу

% Початкові значення
x(1) = x0;
v(1) = v0;
time(1) = 0;

% Чисельне розв'язання методом скінченних різниць
for i = 1:N-1
    % Обчислення нових значень x та v
    x(i+1) = x(i) + v(i)*dt;
    v(i+1) = v(i) - (k/m)*x(i)*dt;
    % Оновлення часу
    time(i+1) = time(i) + dt;
end

% Візуалізація результатів
plot(time, x, 'b-', 'LineWidth', 2);
hold on;
plot(time, v, 'r--', 'LineWidth', 2);
xlabel('Час');
ylabel('Значення');
legend('x', 'v');
title('Чисельний розвязок динамічної системи другого порядку');
grid on;
