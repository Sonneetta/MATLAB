k = (1:300)';

% формирование полезного сигнала
s = sin(2*pi*0.01*k) + sin(2*pi*0.005*k);

% Получение некоррелированного шума
n1 = 0.8*randn(300, 1);

% Фильтр для шума
f1 = [1, 0.5]; 

% Коррелированный шум на основном входе
n = filter(1, f1, n1); 

% Сумма сигнал и шум
d = s + n; 

% Фильтр для шума на основном входе
f2 = [1, -0.8, 0.4, -0.2];

% Шум на опорном входе
x = filter(f2, 1, n1); 

% Порядок фильтра
L = 2; 

% Функция firwiener (в MATLAB нет встроенной функции firwiener, необходимо реализовать самостоятельно)
fw = firwiener(L-1, x, d); % синтез (расчет) фильтра Винера

% Винеровская фильтрация шума
yw = filter(fw, 1, x); 

% Винеровская оценка полезного сигнала
ew = d - yw; 

% Построение графиков
figure;
plot(k, [ew, s, d]);
legend('Фильтр Винера', 'Полезный сигнал', 'Сигнал с шумом');
title('L = 2');
xlabel('Индекс времени k');
ylabel('Амплитуда');

% Реализация функции firwiener
function B = firwiener(N, X, Y)
    % Автокорреляция входного сигнала
    Rxx = xcorr(X, 'biased');
    Rxx = Rxx(length(X):(length(X)+N));
    
    % Кросс-корреляция между входным и выходным сигналами
    Rxy = xcorr(X, Y, 'biased');
    Rxy = Rxy(length(X):(length(X)+N));
    
    % Решение уравнений Йюля-Вокера
    Rxx_matrix = toeplitz(Rxx(1:N+1));
    B = Rxx_matrix \ Rxy(1:N+1);
end
